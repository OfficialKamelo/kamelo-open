// Bewust niet herkend (zie de reden). Telt wel mee in het percentage.
const KNOWN_MISSES = new Set([
  // Geen ik/mijn: "call me" telt niet als over jezelf ("leg me uit"), en debt collector alleen is ook een algemene vraag.
  'can a debt collector call me at work',
  // "lost it" na "crypto": te vaag om op te zoeken; "all my savings" alleen is geen geldzorg.
  'i put all my savings in crypto and lost it',
  // Gedrag beschreven, geen woord dat het zelf zegt ("barely talks" kan ook over een api gaan).
  'my teenage son barely talks and stays in his room all day',
  // "kan niks meer" is ook "mijn laptop kan niks meer"; een overlijden alleen geeft bewust geen melding (zie topics-corpus).
  'mijn moeder is vorige maand overleden en ik kan niks meer',
]);

let failed = 0;
const rows = [];
let posTotal = 0, posHit = 0;
for (const [area, expect, langs] of AREAS) {
  for (const [lang, list] of Object.entries(langs)) {
    const misses = [];
    for (const item of list) {
      const [text, ...own] = Array.isArray(item) ? item : [item];
      const ok = own.length ? own : expect;
      if (!sensitiveTopics(text).some(k => ok.includes(k))) misses.push(text);
    }
    posTotal += list.length; posHit += list.length - misses.length;
    const rate = (list.length - misses.length) / list.length;
    rows.push(`  ${area.padEnd(20)} ${lang}  ${String(list.length - misses.length).padStart(2)}/${list.length}  ${Math.round(rate * 100)}%`);
    for (const m of misses) rows.push(`      ${KNOWN_MISSES.has(m) ? '(bewust)' : '✗'} ${m}  → ${JSON.stringify(sensitiveTopics(m))}`);
    if (rate < 0.9) failed++;
  }
}
let negTotal = 0, negHit = 0;
for (const [lang, list] of Object.entries(NEGATIVE)) {
  for (const t of list) {
    negTotal++;
    const found = sensitiveTopics(t);
    if (found.length) { negHit++; failed++; rows.push(`  ✗ vals alarm (${lang}) ${t}  → ${JSON.stringify(found)}`); }
  }
}

console.log('Alledaagse persoonlijke vragen');
console.log(rows.join('\n'));
