let failed = 0;
const rows = [];
let posTotal = 0, posHit = 0;
for (const [topic, langs] of Object.entries(POSITIVE)) {
  for (const [lang, list] of Object.entries(langs)) {
    const misses = list.filter(t => !sensitiveTopics(t).includes(topic));
    posTotal += list.length; posHit += list.length - misses.length;
    const rate = (list.length - misses.length) / list.length;
    rows.push(`  ${topic.padEnd(9)} ${lang}  ${String(list.length - misses.length).padStart(2)}/${list.length}  ${Math.round(rate * 100)}%`);
    for (const m of misses) {
      const tag = KNOWN_MISSES.has(m) ? '(bewust)' : '✗';
      rows.push(`      ${tag} ${m}  → ${JSON.stringify(sensitiveTopics(m))}`);
    }
    // Engels en Nederlands: minstens 90% per onderwerp; DE/FR/ES zijn steekproeven van 3: minstens 2.
    const min = lang === 'en' || lang === 'nl' ? 0.9 : 2 / 3;
    if (rate < min) failed++;
  }
}
let negTotal = 0, negHit = 0;
for (const [lang, list] of Object.entries(NEGATIVE)) {
  for (const t of list) {
    negTotal++;
    const found = sensitiveTopics(t);
    if (found.length) { negHit++; failed++; rows.push(`  ✗ vals alarm (${lang}) ${t}  → ${JSON.stringify(found)}`); }
  }
}

console.log('Corpus gevoelige onderwerpen');
console.log(rows.join('\n'));
console.log(`\n  herkend: ${posHit}/${posTotal} (${(100 * posHit / posTotal).toFixed(1)}%), vals alarm: ${negHit}/${negTotal}`);
if (posHit / posTotal < 0.95) failed++;
console.log(failed ? `\n${failed} mislukt` : '\nalles geslaagd');
